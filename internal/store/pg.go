// baselineMigrations are the migrations that const schema already folds
// into the table definitions above (kind/speaker, attachments, speaker_openid,
// quote_index, records.delivery, scheduled_tasks.creator_openid,
// messages.addressed and their backfills).
//
// A fresh PostgreSQL database would otherwise run them once: their ALTER TABLE
// steps are guarded by a PRAGMA-based column probe (tableColumns speaks SQLite
// only), and their backfill UPDATEs are pointless on an empty database. Recording
// them as applied makes runMigrations skip every one of them, which is exactly
// how a fresh SQLite database behaves after its first boot.
var baselineMigrations = []string{
	"0001_messages_kind_speaker",
	"0002_backfill_message_speakers",
	"0003_backfill_shared_speakers",
	"0004_messages_attachments",
	"0005_messages_speaker_openid",
	"0006_backfill_message_speaker_openid",
	"0007_records_delivery",
	"0008_messages_quote_index",
	"0009_tasks_creator",
	"0010_messages_addressed",
	"0011_commitments",
	"0012_human_status",
}

// pingTimeout bounds the reachability check at open time: a wrong DSN or a
// stopped server must fail startup quickly instead of hanging the bot.
const pingTimeout = 5 * time.Second

// scanLocation is the fixed zone timestamptz values are scanned into.
//
// Asia/Shanghai has been a constant +08:00 offset since 1991 (no DST), so a
// fixed zone is exact and avoids depending on tzdata. It also matches the
// suffix the migration verifier's to_char(.. AT TIME ZONE 'Asia/Shanghai')
// projection renders.
var scanLocation = time.FixedZone("CST", 8*3600)

// overrideTimestamptzScanLocation installs a timestamptz codec that returns
// its time.Time in +08:00.
//
// Why it is needed: database/sql turns a time.Time into a string with
// RFC3339Nano, so the zone of the scanned time.Time is the zone the Go
// strings carry. pgx decodes timestamptz to UTC by default (and the
// timezone DSN parameter does not change that), which would make every read
// come back as "...Z". RegisterType overwrites the built-in OID mapping in
// place; it is registered for every new connection because stdlib pools
// them, and registering twice on the same map is idempotent.
func overrideTimestamptzScanLocation(_ context.Context, conn *pgx.Conn) error {
	conn.TypeMap().RegisterType(&pgtype.Type{
		Name:  "timestamptz",
		OID:   pgtype.TimestamptzOID,
		Codec: &pgtype.TimestamptzCodec{ScanLocation: scanLocation},
	})
	return nil
}

// openPostgres opens a PostgreSQL database and applies pgSchema plus the
// migration baseline.
func openPostgres(dsn string) (*Store, error) {
	// ParseConfig + stdlib.OpenDB instead of sql.Open("pgx", dsn): the
	// after-connect hook is the only supported way to override a codec before
	// the pool starts handing out connections.
	cfg, err := pgx.ParseConfig(dsn)
	if err != nil {
		return nil, fmt.Errorf("store: parse postgres DSN: %w", err)
	}
	db := stdlib.OpenDB(*cfg, stdlib.OptionAfterConnect(overrideTimestamptzScanLocation))
	// A single bot instance keeps a handful of queries in flight at most; eight
	// connections leave room for the admin API and the background workers without
	// letting a leaked query drain a shared server.
	db.SetMaxOpenConns(8)
	db.SetMaxIdleConns(8)

	ctx, cancel := context.WithTimeout(context.Background(), pingTimeout)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		_ = db.Close()
		return nil, fmt.Errorf("store: ping postgres: %w", err)
	}

	s := &Store{db: db, path: redactDSN(dsn)}
	// Placeholders become $1, $2, … from here on (see dialect.go).
	s.SetDialect(NewDialect(DriverPostgres))

	migrateCtx, cancelMigrate := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancelMigrate()
	if err := s.migratePostgres(migrateCtx); err != nil {
		_ = db.Close()
		return nil, err
	}
	return s, nil
}

// migratePostgres creates the tables and records the migration baseline.
//
// It is the PostgreSQL counterpart of migrate: the SQLite schema is never
// executed here (PRAGMA, AUTOINCREMENT and BLOB are not PostgreSQL), and PRAGMA
// statements do not appear in this path at all.
func (s *Store) migratePostgres(ctx context.Context) error {
	if _, err := s.db.ExecContext(ctx, pgSchema); err != nil {
		return fmt.Errorf("store: migrate postgres: %w", err)
	}
	if err := s.normalizeMemoriesUnique(ctx); err != nil {
		return fmt.Errorf("store: migrate postgres: %w", err)
	}
	return s.seedMigrationBaseline(ctx)
}

// legacyMemoriesUnique is the constraint name older versions of pgSchema wrote.
// It is kept only so an already-deployed database can be renamed in place.
const legacyMemoriesUnique = "uq_memories_scope_group_openid_member_openid_text"

// memoriesUnique is the name both schema sources agree on now.
const memoriesUnique = "memories_scope_group_openid_member_openid_text_key"

// memoriesUniqueProbe reports, for the memories table, the column list of the
// constraint carrying the legacy name and of the one carrying the shared name.
// A NULL means the constraint is absent. conkey::text is the ordered list of
// column numbers the constraint covers, so two entries with the same text are
// the same unique index under two names.
const memoriesUniqueProbe = `SELECT
  (SELECT conkey::text FROM pg_constraint WHERE conname = $1 AND conrelid = 'memories'::regclass),
  (SELECT conkey::text FROM pg_constraint WHERE conname = $2 AND conrelid = 'memories'::regclass)`

// pgIdent quotes a PostgreSQL identifier. The two constraint names above are
// compile-time constants, but quoting them keeps the statement correct if a
// future name ever needs it.
func pgIdent(name string) string { return `"` + strings.ReplaceAll(name, `"`, `""`) + `"` }

// normalizeMemoriesUnique brings a database created by an older build onto the
// shared constraint name.
//
// Why: pgSchema used to spell the memories UNIQUE constraint "uq_memories_…",
// while internal/pgmigrate synthesizes the name PostgreSQL would have picked
// ("…_key"). A database created by the store and then visited by the migrator
// therefore ended up with two identical unique indexes — same columns, same
// semantics, one extra B-tree and one extra uniqueness check per write.
// CREATE TABLE IF NOT EXISTS cannot fix that on an existing database, and
// RENAME CONSTRAINT has no IF EXISTS, so the catalog is consulted first.
//
// Three cases, all idempotent:
//
//	legacy only   → rename it (nothing is dropped, no write is blocked)
//	both present  → drop the legacy one, but only when both cover exactly the
//	                same columns; otherwise leave both alone (losing a
//	                constraint that covers different columns would be data loss)
//	shared only   → nothing to do (the normal state after this change)
//
// Reversible: the reverse migration is the same statement with the two
// constants swapped, which is why they are constants rather than literals.
func (s *Store) normalizeMemoriesUnique(ctx context.Context) error {
	var legacyCols, currentCols sql.NullString
	if err := s.db.QueryRowContext(ctx, memoriesUniqueProbe,
		legacyMemoriesUnique, memoriesUnique).Scan(&legacyCols, &currentCols); err != nil {
		return fmt.Errorf("probe memories unique constraint: %w", err)
	}
	switch {
	case !legacyCols.Valid:
		// Fresh database (already created with the shared name) or already
		// normalized: nothing to do.
		return nil
	case !currentCols.Valid:
		stmt := "ALTER TABLE memories RENAME CONSTRAINT " +
			pgIdent(legacyMemoriesUnique) + " TO " + pgIdent(memoriesUnique)
		if _, err := s.db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("rename memories unique constraint: %w", err)
		}
		return nil
	case legacyCols.String != currentCols.String:
		// Two different constraints that happen to share a table: not ours to
		// judge, so leave both in place.
		return nil
	default:
		// Both names cover the same columns: the legacy one is pure overhead.
		stmt := "ALTER TABLE memories DROP CONSTRAINT " + pgIdent(legacyMemoriesUnique)
		if _, err := s.db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("drop redundant memories unique constraint: %w", err)
		}
		return nil
	}
}

// seedMigrationBaseline marks the baseline migrations as applied.
//
// ON CONFLICT DO NOTHING keeps this idempotent: the rows are written on the first
// open and every later open is a no-op, so a database that already carries a real
// applied_at value keeps it.
func (s *Store) seedMigrationBaseline(ctx context.Context) error {
	now := nowRFC3339()
	for _, name := range baselineMigrations {
		if _, err := s.db.ExecContext(ctx,
			`INSERT INTO schema_migrations (name, applied_at) VALUES ($1, $2)
ON CONFLICT (name) DO NOTHING`, name, now); err != nil {
			return fmt.Errorf("store: baseline migration %s: %w", name, err)
		}
	}
	return nil
}

// postgresSizeBytes asks the server how large the current database is.
//
// pg_database_size is the only honest answer PostgreSQL offers for "how big is
// this database": there is no local file to stat, and a table-level sum would
// miss indexes, TOAST and free space. A failure (permissions, a closed handle,
// a timeout) returns 0 so the admin status endpoint can render "unknown"
// instead of failing the whole request.
func (s *Store) postgresSizeBytes() int64 {
	ctx, cancel := context.WithTimeout(context.Background(), sizeQueryTimeout)
	defer cancel()
	var size int64
	if err := s.db.QueryRowContext(ctx,
		`SELECT pg_database_size(current_database())`).Scan(&size); err != nil {
		return 0
	}
	return size
}

// sizeQueryTimeout bounds the database-size probe; it runs on the status
// endpoint's request path, so it must not be able to hang the panel.
const sizeQueryTimeout = 3 * time.Second

// redactDSN hides the password before the DSN is kept on the Store, so a future
// diagnostic that prints Store.Target() cannot leak the database credential.
func redactDSN(dsn string) string {
	u, err := url.Parse(strings.TrimSpace(dsn))
	if err != nil || u.Scheme == "" || u.Host == "" {
		return "postgres://(redacted)"
	}
	if u.User != nil {
		u.User = url.UserPassword(u.User.Username(), "redacted")
	}
	return u.String()
}
